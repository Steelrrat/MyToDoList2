    private Date resolveReminderDate() {
        if (tempDate == null || (tempHour >= 0 && tempMinute >= 0)) {
            return tempDate;
        }

        if (!tempDateChangedForReminder) {
            return tempDate;
        }

        Calendar selectedDate = Calendar.getInstance();
        selectedDate.setTime(tempDate);

        Calendar now = Calendar.getInstance();
        selectedDate.set(Calendar.HOUR_OF_DAY, now.get(Calendar.HOUR_OF_DAY));
        selectedDate.set(Calendar.MINUTE, now.get(Calendar.MINUTE));
        selectedDate.set(Calendar.SECOND, 0);
        selectedDate.set(Calendar.MILLISECOND, 0);
        return selectedDate.getTime();
    }

    private void showNotificationTimeToast(Task task) {
        Calendar notifyTime = task.getNotificationCalendar();
        if (notifyTime == null) {
            return;
        }

        long diffMillis = notifyTime.getTimeInMillis() - System.currentTimeMillis();
        if (diffMillis <= 0) {
            Toast.makeText(this, "Выберите будущие дату и время", Toast.LENGTH_SHORT).show();
            return;
        }

        long totalMinutes = Math.max(1, (diffMillis + 59_999) / 60_000);
        long days = totalMinutes / (24 * 60);
        long hours = (totalMinutes % (24 * 60)) / 60;
        long minutes = totalMinutes % 60;

        ArrayList<String> parts = new ArrayList<>();
        if (days > 0) {
            parts.add(days + " " + getRussianPlural(days, "день", "дня", "дней"));
        }
        if (hours > 0) {
            parts.add(hours + " " + getRussianPlural(hours, "час", "часа", "часов"));
        }
        if (minutes > 0) {
            parts.add(minutes + " " + getRussianPlural(minutes, "минута", "минуты", "минут"));
        }

        String duration;
        if (parts.size() == 1) {
            duration = parts.get(0);
        } else if (parts.size() == 2) {
            duration = parts.get(0) + " и " + parts.get(1);
        } else {
            duration = parts.get(0) + ", " + parts.get(1) + " и " + parts.get(2);
        }

        Toast.makeText(
                this,
                "🔔 Напоминание сработает через " + duration,
                Toast.LENGTH_LONG
        ).show();
    }

    private String getRussianPlural(long value, String one, String few, String many) {
        long lastTwoDigits = value % 100;
        if (lastTwoDigits >= 11 && lastTwoDigits <= 14) {
            return many;
        }

        long lastDigit = value % 10;
        if (lastDigit == 1) {
            return one;
        }
        if (lastDigit >= 2 && lastDigit <= 4) {
            return few;
        }
        return many;
    }

    private void showDatePicker(TextView targetTextView) {
        Calendar c = Calendar.getInstance();

        DatePickerDialog dialog = new DatePickerDialog(this, (view1, year, month, day) -> {
            Calendar selected = Calendar.getInstance();
            selected.set(year, month, day, 0, 0, 0);
            selected.set(Calendar.MILLISECOND, 0);

            tempDate = selected.getTime();
            tempDateChangedForReminder = true;
            updateDateDisplay(targetTextView);

            if (currentDialog != null) {
                TextView txtTime = currentDialog.findViewById(R.id.textEditTime);
                if (txtTime != null) {
                    updateTimeDisplay(txtTime);
                }
            }
        }, c.get(Calendar.YEAR), c.get(Calendar.MONTH), c.get(Calendar.DAY_OF_MONTH));

        Calendar today = Calendar.getInstance();
        today.set(Calendar.HOUR_OF_DAY, 0);
        today.set(Calendar.MINUTE, 0);
        today.set(Calendar.SECOND, 0);
        today.set(Calendar.MILLISECOND, 0);

        dialog.getDatePicker().setMinDate(today.getTimeInMillis());
        dialog.show();
    }
    private void showTimePicker(TextView txtDate, TextView txtTime) {
        Calendar c = Calendar.getInstance();

        int hour = tempHour >= 0
                ? tempHour
                : c.get(Calendar.HOUR_OF_DAY);

        int minute = tempMinute >= 0
                ? tempMinute
                : c.get(Calendar.MINUTE);

        new TimePickerDialog(this, (view1, hourOfDay, minuteOfHour) -> {
            if (tempDate != null) {
                Calendar selectedDateTime = Calendar.getInstance();
                selectedDateTime.setTime(tempDate);
                selectedDateTime.set(Calendar.HOUR_OF_DAY, hourOfDay);
                selectedDateTime.set(Calendar.MINUTE, minuteOfHour);
                selectedDateTime.set(Calendar.SECOND, 0);
                selectedDateTime.set(Calendar.MILLISECOND, 0);

                Calendar now = Calendar.getInstance();

                if (selectedDateTime.getTimeInMillis() <= now.getTimeInMillis()) {
                    Toast.makeText(
                            this,
                            "Выберите будущее время",
                            Toast.LENGTH_SHORT
                    ).show();
                    return;
                }
            }

            tempHour = hourOfDay;
            tempMinute = minuteOfHour;

            updateDateDisplay(txtDate);
            updateTimeDisplay(txtTime);

        }, hour, minute, true).show();
    }
    private void updateDateDisplay(TextView txtDate) {
        if (txtDate == null) return;

        // Определяем цвет для даты
        SharedPreferences themePrefs = getSharedPreferences(PREFS_THEME, MODE_PRIVATE);
        boolean isDark = themePrefs.getBoolean(THEME_KEY, false);
        int accentColor;
        if (isDark) {
            accentColor = ContextCompat.getColor(this, R.color.dark_accent);
        } else {
            accentColor = ContextCompat.getColor(this, R.color.light_accent);
        }
        txtDate.setTextColor(ContextCompat.getColor(this, R.color.dialog_control_text));

        if (tempDate != null) {
            SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy", Locale.getDefault());
            String dateStr = sdf.format(tempDate);
            // Только дата, без времени
            txtDate.setText(dateStr);
        } else {
            txtDate.setText("Введите дату");
        }
    }

